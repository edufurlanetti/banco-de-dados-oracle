-- Remove objetos de execuções anteriores (ignora "tabela não existe")
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('HISTORICO_SALARIO','FUNCIONARIO','CARGO','DEPARTAMENTO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

CREATE TABLE departamento (
    id_departamento NUMBER(4)     GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(60)  NOT NULL,
    cidade          VARCHAR2(60)  NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
    CONSTRAINT uq_departamento_nome UNIQUE (nome)
);

CREATE TABLE cargo (
    id_cargo       NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
    titulo         VARCHAR2(60) NOT NULL,
    salario_minimo NUMBER(10,2) NOT NULL,
    salario_maximo NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_cargo PRIMARY KEY (id_cargo),
    CONSTRAINT ck_cargo_faixa CHECK (salario_maximo >= salario_minimo)
);

CREATE TABLE funcionario (
    id_funcionario  NUMBER(6)     GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(100) NOT NULL,
    email           VARCHAR2(120) NOT NULL,
    data_admissao   DATE          DEFAULT SYSDATE NOT NULL,
    salario         NUMBER(10,2)  NOT NULL,
    id_cargo        NUMBER(4)     NOT NULL,
    id_departamento NUMBER(4)     NOT NULL,
    id_gestor       NUMBER(6),                       -- autorrelacionamento (hierarquia)
    ativo           CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_funcionario PRIMARY KEY (id_funcionario),
    CONSTRAINT uq_funcionario_email UNIQUE (email),
    CONSTRAINT fk_func_cargo  FOREIGN KEY (id_cargo)        REFERENCES cargo (id_cargo),
    CONSTRAINT fk_func_depto  FOREIGN KEY (id_departamento) REFERENCES departamento (id_departamento),
    CONSTRAINT fk_func_gestor FOREIGN KEY (id_gestor)       REFERENCES funcionario (id_funcionario),
    CONSTRAINT ck_func_salario CHECK (salario > 0),
    CONSTRAINT ck_func_ativo   CHECK (ativo IN ('S', 'N'))
);

CREATE INDEX ix_func_depto  ON funcionario (id_departamento);
CREATE INDEX ix_func_gestor ON funcionario (id_gestor);

CREATE TABLE historico_salario (
    id_historico    NUMBER(8)    GENERATED ALWAYS AS IDENTITY,
    id_funcionario  NUMBER(6)    NOT NULL,
    salario_antigo  NUMBER(10,2) NOT NULL,
    salario_novo    NUMBER(10,2) NOT NULL,
    data_alteracao  DATE         DEFAULT SYSDATE NOT NULL,
    usuario         VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT pk_historico_salario PRIMARY KEY (id_historico),
    CONSTRAINT fk_hist_funcionario FOREIGN KEY (id_funcionario)
        REFERENCES funcionario (id_funcionario)
);
